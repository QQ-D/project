"""Compact controls for the independent offline Mandarin TTS workflow."""
from PyQt5.QtCore import Qt
from PyQt5.QtWidgets import (QWidget, QVBoxLayout, QHBoxLayout, QLabel,
                             QPlainTextEdit, QPushButton, QDoubleSpinBox, QSlider)


def make_tts_panel(host):
    panel = QWidget()
    layout = QVBoxLayout(panel)
    layout.setContentsMargins(0, 0, 0, 0)
    host.tts_engine_label = QLabel(host._tts_engine_message)
    host.tts_engine_label.setWordWrap(True)
    layout.addWidget(host.tts_engine_label)
    note = QLabel('文字仅在本机处理；合成不会自动播放。送入工作台后替换原声，已有底噪需重新确认。')
    note.setWordWrap(True)
    layout.addWidget(note)
    host.tts_text = QPlainTextEdit()
    host.tts_text.setPlaceholderText('输入中文（最多400字符），例如：欢迎来到数字信号处理实验。')
    host.tts_text.setMinimumHeight(100)
    host.tts_text.setMaximumHeight(180)
    layout.addWidget(host.tts_text)
    host.tts_count_label = QLabel('0 / 400 字符')
    layout.addWidget(host.tts_count_label)
    speed_row = QHBoxLayout()
    speed_row.addWidget(QLabel('合成语速'))
    host.tts_speed_slider = QSlider(Qt.Horizontal)
    host.tts_speed_slider.setRange(50, 200)
    host.tts_speed_slider.setValue(100)
    host.tts_speed_spin = QDoubleSpinBox()
    host.tts_speed_spin.setDecimals(2)
    host.tts_speed_spin.setRange(.5, 2)
    host.tts_speed_spin.setSingleStep(.05)
    host.tts_speed_spin.setValue(1)
    host.tts_speed_spin.setSuffix(' ×')
    host.tts_speed_slider.valueChanged.connect(lambda value: host.tts_speed_spin.setValue(value/100))
    host.tts_speed_spin.valueChanged.connect(lambda value: host.tts_speed_slider.setValue(round(value*100)))
    speed_row.addWidget(host.tts_speed_slider)
    speed_row.addWidget(host.tts_speed_spin)
    layout.addLayout(speed_row)
    host.tts_generate_button = QPushButton('生成中文语音')
    host.tts_generate_button.setProperty('primary', True)
    host.tts_generate_button.clicked.connect(host.start_tts)
    layout.addWidget(host.tts_generate_button)
    host.tts_result_label = QLabel('尚未生成；音色固定为基础普通话。')
    host.tts_result_label.setWordWrap(True)
    layout.addWidget(host.tts_result_label)
    preview_row = QHBoxLayout()
    host.tts_play_button = QPushButton('▶ 试听合成')
    host.tts_stop_button = QPushButton('■ 停止')
    host.tts_play_button.clicked.connect(host.play_tts)
    host.tts_stop_button.clicked.connect(host.tts_player.stop)
    preview_row.addWidget(host.tts_play_button)
    preview_row.addWidget(host.tts_stop_button)
    layout.addLayout(preview_row)
    host.tts_progress_label = QLabel('0.00 / 0.00 s')
    layout.addWidget(host.tts_progress_label)
    host.tts_save_button = QPushButton('保存合成 WAV')
    host.tts_save_button.clicked.connect(host._choose_tts_save)
    layout.addWidget(host.tts_save_button)
    host.tts_send_button = QPushButton('送入工作台作为原声')
    host.tts_send_button.clicked.connect(host.send_tts_to_workbench)
    layout.addWidget(host.tts_send_button)
    host.tts_text.textChanged.connect(host._tts_changed)
    host.tts_speed_spin.valueChanged.connect(host._tts_changed)
    layout.addStretch()
    host._tts_controls()
    return panel
