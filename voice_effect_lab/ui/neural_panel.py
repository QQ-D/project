"""智能降噪的模型选择、教学训练与同源对比控制。"""
from PyQt5.QtCore import Qt
from PyQt5.QtWidgets import (QWidget, QVBoxLayout, QHBoxLayout, QLabel, QPushButton,
                             QSpinBox, QSlider, QComboBox, QPlainTextEdit)


def make_neural_panel(host):
    panel = QWidget()
    layout = QVBoxLayout(panel)
    layout.setContentsMargins(0, 0, 0, 0)

    def label(name, text, parent_layout=None):
        widget = QLabel(text)
        widget.setWordWrap(True)
        setattr(host, name, widget)
        (parent_layout if parent_layout is not None else layout).addWidget(widget)
        return widget

    def button(name, text, callback, parent_layout=None):
        widget = QPushButton(text)
        widget.clicked.connect(callback)
        setattr(host, name, widget)
        (parent_layout if parent_layout is not None else layout).addWidget(widget)
        return widget

    label('neural_source_label', '在基础工作台导入原声，或载入下方公开加噪演示。')
    host.neural_engine_combo = QComboBox()
    host.neural_engine_combo.addItem('DeepFilterNet3 · 预训练模型', 'deepfilter')
    host.neural_engine_combo.addItem('小型 BP · 教学训练', 'bp')
    layout.addWidget(host.neural_engine_combo)
    label('neural_scope_label', '')
    label('neural_unavailable_label', '')

    host.deepfilter_parameters = QWidget()
    df = QVBoxLayout(host.deepfilter_parameters)
    df.setContentsMargins(0, 0, 0, 0)
    row = QHBoxLayout()
    row.addWidget(QLabel('模型混合'))
    host.deepfilter_strength_slider = QSlider(Qt.Horizontal)
    host.deepfilter_strength_slider.setRange(0, 100)
    host.deepfilter_strength_slider.setValue(100)
    row.addWidget(host.deepfilter_strength_slider)
    host.deepfilter_strength_spin = QSpinBox()
    host.deepfilter_strength_spin.setRange(0, 100)
    host.deepfilter_strength_spin.setValue(100)
    host.deepfilter_strength_spin.setSuffix('%')
    host.deepfilter_strength_spin.setToolTip('100%为完整模型输出，0%为原声；中间值混合两者。')
    row.addWidget(host.deepfilter_strength_spin)
    host.deepfilter_strength_slider.valueChanged.connect(host.deepfilter_strength_spin.setValue)
    host.deepfilter_strength_spin.valueChanged.connect(host.deepfilter_strength_slider.setValue)
    df.addLayout(row)
    layout.addWidget(host.deepfilter_parameters)

    host.neural_training_panel = QWidget()
    training = QVBoxLayout(host.neural_training_panel)
    training.setContentsMargins(0, 0, 0, 0)
    label('neural_model_label', '模型未就绪，请训练或加载本项目 NPZ。', training)
    label('neural_training_label', '训练数据：公开合成谐波与噪声（默认）。', training)
    button('neural_training_synthetic_button', '使用公开合成训练数据', host._neural_use_synthetic, training)
    button('neural_training_load_button', '导入干净训练 WAV（2–60 秒）', host._neural_choose_training, training)
    row = QHBoxLayout()
    row.addWidget(QLabel('训练轮数'))
    host.neural_epochs_spin = QSpinBox()
    host.neural_epochs_spin.setRange(1, 100)
    host.neural_epochs_spin.setValue(20)
    row.addWidget(host.neural_epochs_spin)
    row.addWidget(QLabel('批大小'))
    host.neural_batch_spin = QSpinBox()
    host.neural_batch_spin.setRange(32, 512)
    host.neural_batch_spin.setValue(128)
    row.addWidget(host.neural_batch_spin)
    training.addLayout(row)
    button('neural_train_button', '训练小型 BP 网络', host.start_neural_training, training).setProperty('primary', True)
    row = QHBoxLayout()
    button('neural_model_save_button', '保存模型 NPZ', host._neural_choose_model_save, row)
    button('neural_model_load_button', '加载模型 NPZ', host._neural_choose_model_load, row)
    training.addLayout(row)
    host.neural_log = QPlainTextEdit()
    host.neural_log.setReadOnly(True)
    host.neural_log.setMaximumBlockCount(300)
    host.neural_log.setMaximumHeight(115)
    host.neural_log.setPlaceholderText('训练逐轮显示真实训练/验证损失。')
    training.addWidget(host.neural_log)
    row = QHBoxLayout()
    row.addWidget(QLabel('BP 强度'))
    host.neural_strength_slider = QSlider(Qt.Horizontal)
    host.neural_strength_slider.setRange(0, 100)
    host.neural_strength_slider.setValue(75)
    row.addWidget(host.neural_strength_slider)
    host.neural_strength_label = QLabel('75%', host.neural_training_panel)
    host.neural_strength_label.setVisible(False)
    host.neural_strength_spin = QSpinBox()
    host.neural_strength_spin.setRange(0, 100)
    host.neural_strength_spin.setValue(75)
    host.neural_strength_spin.setSuffix('%')
    row.addWidget(host.neural_strength_spin)
    host.neural_strength_slider.valueChanged.connect(host.neural_strength_spin.setValue)
    host.neural_strength_spin.valueChanged.connect(host.neural_strength_slider.setValue)
    training.addLayout(row)
    layout.addWidget(host.neural_training_panel)

    button('neural_demo_button', '载入公开加噪演示（含干净参考）', host.load_neural_demo)
    label('neural_baseline_label', '同一份原声比较，传统基线固定：自动维纳 60%。')
    button('neural_compare_button', '运行模型 / 维纳比较', host.run_neural_comparison).setProperty('primary', True)
    label('neural_metrics_label', '尚无比较结果；无干净参考时 SNR 显示 —。')
    host.neural_selection_combo = QComboBox()
    for text, data in [('原声', 'source'), ('传统维纳 60%', 'traditional'),
                       ('DeepFilterNet3', 'deepfilter'), ('小型 BP', 'bp')]:
        host.neural_selection_combo.addItem(text, data)
    host.neural_selection_combo.setCurrentIndex(2)
    layout.addWidget(host.neural_selection_combo)
    row = QHBoxLayout()
    button('neural_play_button', '▶ 试听所选', host.play_neural, row)
    button('neural_stop_button', '■ 停止', host.neural_player.stop, row)
    layout.addLayout(row)
    label('neural_progress_label', '0.00 / 0.00 s')
    label('neural_volume_note', '试听音量和静音与基础页、TTS同步。')
    button('neural_plots_button', '放大查看所选六图', host.show_neural_plots)
    button('neural_save_button', '保存所选 WAV', host._neural_choose_save)
    button('neural_send_button', '送入主工作台作为新原声', host.send_neural_to_workbench)
    label('neural_send_note', '只有点击送入才替换工作台原声及处理缓存；训练数据和模型独立保留。')
    host.neural_strength_slider.valueChanged.connect(host._neural_strength_changed)
    host.deepfilter_strength_spin.valueChanged.connect(host._deepfilter_strength_changed)
    host.neural_engine_combo.currentIndexChanged.connect(host._neural_engine_changed)
    host.neural_selection_combo.currentIndexChanged.connect(host._neural_selection_changed)
    host.neural_epochs_spin.valueChanged.connect(host._neural_training_changed)
    host.neural_batch_spin.valueChanged.connect(host._neural_training_changed)
    layout.addStretch()
    host._neural_engine_changed()
    return panel
